// Builds src/data/tidePorts.js: each port's lunitidal interval (hours from the Moon's transit to high water),
// worked out from published high-water times. The app uses it only as a labelled fallback estimate when the
// server has no official (Admiralty) predictions. Usage: node tools/calibrate-tides.mjs research/tides.json
import { readFileSync, writeFileSync } from "node:fs";
import ASTRO from "../src/lib/astro.js";

const src = process.argv[2];
const rows = JSON.parse(readFileSync(src, "utf8"));
const P = 12.4206;
const byPort = new Map();
for (const r of rows) {
  if (!r.high_waters?.length || r.lat == null) continue;
  const tz = /BST|\+01/.test(r.tz || "") && !/ended/.test(r.tz || "") ? 1 : 0;
  const [y, m, d] = r.date.split("-").map(Number);
  for (const hw of r.high_waters) {
    const [hh, mm] = hw.time.split(":").map(Number);
    const t = Date.UTC(y, m - 1, d, hh - tz, mm);
    const trs = ASTRO.transits(t - 14 * 3600e3, t, r.lon);
    const prev = trs.filter((x) => x <= t).pop();
    if (!prev) continue;
    const li = ((((t - prev) / 3600e3) - ASTRO.priming(t)) % P + P) % P; // mean interval, priming removed
    const e = byPort.get(r.port) || { port: r.port, lat: r.lat, lon: r.lon, lis: [], src: new Set() };
    e.lis.push(li); if (r.source_url) e.src.add(r.source_url.replace(/-\d{8}$/, ""));
    byPort.set(r.port, e);
  }
}
const out = [];
for (const e of byPort.values()) {
  // circular mean on a 12.42 h cycle
  let sx = 0, sy = 0;
  for (const li of e.lis) { const a = (2 * Math.PI * li) / P; sx += Math.cos(a); sy += Math.sin(a); }
  const li = ((Math.atan2(sy, sx) / (2 * Math.PI)) * P + P) % P;
  const spread = Math.max(...e.lis.map((x) => Math.min(Math.abs(x - li), P - Math.abs(x - li))));
  out.push({ port: e.port, lat: +e.lat.toFixed(4), lon: +e.lon.toFixed(4), li: +li.toFixed(2), n: e.lis.length, spreadH: +spread.toFixed(2) });
}
out.sort((a, b) => a.port.localeCompare(b.port));
const file = `// Generated by tools/calibrate-tides.mjs from published high-water times (31 Oct and 1 Nov 2026, tidetimes.org.uk).
// li = mean hours from the Moon's transit to high water (priming/lagging removed; astro.js adds it back per date). Used only for the labelled on-device estimate; real
// predictions come from the Admiralty UK Tidal API through /api/tides when the server has a key.
export const TIDE_PORTS = ${JSON.stringify(out, null, 0).replace(/\},\{/g, "},\n  {").replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};
`;
writeFileSync(new URL("../src/data/tidePorts.js", import.meta.url), file);
console.log(out.length, "ports;", out.map((p) => `${p.port} ${p.li}h±${p.spreadH}`).join(", "));
